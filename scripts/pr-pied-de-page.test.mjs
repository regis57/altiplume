import { describe, expect, it } from 'vitest';
import { retirerPiedDePage } from './pr-pied-de-page.mjs';

const TEXTE = '## Quoi\n\n- une chose\n- une autre\n\n## Vérifié\n\n- tests verts';
const AVEC_LIEN = '\n\n---\n_Generated by [Outil](https://exemple.test/code/session_01AbC-xyz)_';
const SANS_LIEN = '\n\n---\n_Generated by [Outil](https://exemple.test/code)_';

describe('retirerPiedDePage', () => {
  it('retire la signature avec lien de session, et le trait qui la sépare', () => {
    expect(retirerPiedDePage(TEXTE + AVEC_LIEN)).toBe(TEXTE);
  });

  it('retire la signature sans lien de session', () => {
    expect(retirerPiedDePage(TEXTE + SANS_LIEN)).toBe(TEXTE);
  });

  it('retire la variante avec emoji, et la ligne de lien de session qui la suit', () => {
    const pied = '\n\n---\n\n🤖 Generated with [Outil](https://exemple.test/code)\n\nhttps://exemple.test/code/session_01AbC\n';
    expect(retirerPiedDePage(TEXTE + pied)).toBe(TEXTE);
  });

  it('garde les fins de ligne Windows du texte, et retire une signature écrite avec elles', () => {
    const win = 'Un\r\n\r\nDeux';
    expect(retirerPiedDePage(win + AVEC_LIEN.replace(/\n/g, '\r\n'))).toBe(win);
  });

  it('ne touche à rien quand il n\'y a pas de signature', () => {
    expect(retirerPiedDePage(TEXTE)).toBe(TEXTE);
    expect(retirerPiedDePage(TEXTE + '\n')).toBe(TEXTE + '\n');
    expect(retirerPiedDePage('')).toBe('');
  });

  it('ne retire que la fin du texte : la même phrase au milieu reste', () => {
    const milieu = 'Avant\n\n_Generated by [Outil](https://exemple.test/code)_\n\nAprès, du vrai texte';
    expect(retirerPiedDePage(milieu)).toBe(milieu);
  });

  it('garde un trait « --- » qui fait partie du texte quand rien ne le suit', () => {
    const avecTrait = 'Un\n\n---\n\nDeux';
    expect(retirerPiedDePage(avecTrait)).toBe(avecTrait);
  });

  it('est idempotent', () => {
    const une = retirerPiedDePage(TEXTE + AVEC_LIEN);
    expect(retirerPiedDePage(une)).toBe(une);
  });

  it('rend une chaîne vide quand la description n\'était que la signature', () => {
    expect(retirerPiedDePage(AVEC_LIEN.trimStart())).toBe('');
  });

  it('accepte une description absente', () => {
    expect(retirerPiedDePage(null)).toBe('');
    expect(retirerPiedDePage(undefined)).toBe('');
  });
});
