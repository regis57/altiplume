const DICT: Record<Locale, Record<string, string>> = { fr: FR, en: EN };

let current: Locale = detect();

function detect(): Locale {
  // Un lien partagé dit sa langue (« ?lang=en ») : il passe avant l'habitude du navigateur,
  // et devient le choix retenu — celui qui ouvre un lien anglais veut lire en anglais.
  const asked = new URLSearchParams(location.search).get('lang');
  if (asked === 'fr' || asked === 'en') {
    try { localStorage.setItem(STORAGE_KEY, asked); } catch { /* sans importance */ }
    return asked;
  }
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'fr' || stored === 'en') return stored;
  } catch { /* stockage indisponible : on retombe sur le navigateur */ }
  return navigator.language.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export function getLocale(): Locale {
  return current;
}

export function setLocale(locale: Locale): void {
  current = locale;
  try { localStorage.setItem(STORAGE_KEY, locale); } catch { /* sans importance */ }
}

/**
 * Date dans la langue courante. `short` : « 11 oct. 2026 » ; `long` : « 11 octobre 2026 ».
 * `utc` : le jour en temps universel, pour une date du calendrier du jeu (les saisons
 * basculent à minuit UTC) ; sinon, le jour à l'heure du joueur.
 */
export function formatDate(ms: number, style: 'short' | 'long' = 'long', utc = false): string {
  const tag = current === 'fr' ? 'fr-FR' : 'en-GB';
  return new Date(ms).toLocaleDateString(tag, {
    ...(style === 'short' ? { day: '2-digit', month: 'short', year: 'numeric' } as const : { day: 'numeric', month: 'long', year: 'numeric' } as const),
    ...(utc ? { timeZone: 'UTC' } : {}),
  });
}

/** Un nombre écrit comme dans la langue : « 12 500 » en français, « 12,500 » en anglais. */
export function formatNumber(n: number): string {
  return n.toLocaleString(current === 'fr' ? 'fr-FR' : 'en-GB');
}

/**
 * La clé au singulier ou au pluriel, selon la règle de la langue : en français, 0 et 1
 * sont au singulier (« 0 page ») ; en anglais, seul 1 l'est (« 0 pages »).
 */
export function plural(n: number, one: string, other: string): string {
  return new Intl.PluralRules(current === 'fr' ? 'fr-FR' : 'en-GB').select(n) === 'one' ? one : other;
}

export function t(key: string): string {
  return DICT[current][key] ?? DICT.fr[key] ?? key;
}

/** Applique la langue courante à toute la page. */
export function translatePage(): void {
  document.documentElement.lang = current;
  document.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    const key = el.dataset['i18n'];
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((el) => {
    const key = el.dataset['i18nHtml'];
    // Les chaînes avec balises viennent du dictionnaire embarqué, jamais du réseau,
    // et passent par la politique Trusted Types « altiplume » (trusted.ts). Examiné
    // pour Opengrep : la seule écriture HTML du client, voulue.
    // nosemgrep: insecure-innerhtml, insecure-document-method
    if (key) el.innerHTML = trustedHtml(t(key));
  });
  // Messages composés de codes (« error.x error.y ») : re-rendus dans la langue courante.
  document.querySelectorAll<HTMLElement>('[data-i18n-keys]').forEach((el) => {
    const keys = (el.dataset['i18nKeys'] ?? '').split(' ').filter(Boolean);
    const count = el.dataset['count'];
    el.textContent = keys.map((k) => t(k)).join(' ')
      .replace('{n}', count === undefined ? '' : Number(count).toLocaleString(current === 'fr' ? 'fr-FR' : 'en-GB'));
  });
  document.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((el) => {
    const key = el.dataset['i18nAria'];
    if (key) el.setAttribute('aria-label', t(key));
  });
  // Dates : l'horodatage est porté par l'élément, le format suit la langue.
  document.querySelectorAll<HTMLElement>('[data-date]').forEach((el) => {
    const ms = Number(el.dataset['date']);
    if (Number.isFinite(ms)) el.textContent = formatDate(ms, el.dataset['dateStyle'] === 'short' ? 'short' : 'long');
  });
  document.querySelectorAll<HTMLElement>('[data-lang]').forEach((el) => {
    el.classList.toggle('cache', el.dataset['lang'] !== current);
  });
  // Le titre de l'onglet suit la langue (une page peut le reprendre : l'aérodrome y met son nom).
  const title = document.documentElement.dataset[current === 'fr' ? 'titleFr' : 'titleEn'];
  if (title) document.title = `${title} — Altiplume`;
  syncLanguageInAddress();
  const toggle = document.querySelector<HTMLButtonElement>('[data-action=toggle-lang]');
  if (toggle) {
    toggle.textContent = current === 'fr' ? 'EN' : 'FR';
    // Le nom lu reprend le texte affiché (« EN », « FR ») : WCAG 2.5.3, étiquette dans le nom.
    toggle.setAttribute('aria-label', current === 'fr' ? 'EN: switch to English' : 'FR : passer en français');
    toggle.lang = current === 'fr' ? 'en' : 'fr';
  }
}

/**
 * L'adresse porte la langue : en anglais, « ?lang=en » ; en français, rien. Ainsi un
 * lien copié depuis la barre d'adresse montre, une fois collé dans une conversation,
 * la carte de partage dans la langue où on lisait. Les autres paramètres sont gardés.
 */
function syncLanguageInAddress(): void {
  const url = new URL(location.href);
  const had = url.searchParams.get('lang');
  if (current === 'en') url.searchParams.set('lang', 'en');
  else url.searchParams.delete('lang');
  if (url.searchParams.get('lang') !== had) history.replaceState(history.state, '', url);
}

/**
 * Une préposition suivie d'un nom de lieu, avec les contractions du français :
 * « rentré de Les Tilleuls » devient « rentré des Tilleuls », « arrivée à Le
 * Hêtre-Roi » devient « arrivée au Hêtre-Roi », « départ pour Les Scieries »
 * devient « départ pour les Scieries ». L'anglais n'a rien à contracter.
 */
export function placeAfter(phrase: string, name: string): string {
  if (current !== 'fr') return `${phrase} ${name}`;
  // L'article écrit (« Les Tilleuls »), ou celui qu'on dit sans l'écrire : on va « à l'Île-du-Bout »,
  // « à l'Anse-des-Lanternes », « au Phare de Brisant ».
  // Un article est suivi d'une espace (ou s'élide) : « Lanterne-du-Val » n'en a pas.
  const written = /^(?:(Les|Le|La) |(L'))(.+)$/.exec(name);
  const spoken = /^(Île|Anse)\b/.test(name) ? ["L'", name] : /^Phare\b/.test(name) ? ['Le', name] : null;
  const m = written ? [written[1] ?? written[2], written[3]] : spoken;
  if (!m) return `${phrase} ${name}`;
  const [article, rest] = m as ['Les' | 'Le' | 'La' | "L'", string];
  const head = phrase.replace(/\s+(de|à)$/, '');
  const prep = /\s(de|à)$/.exec(phrase)?.[1];
  const glued = article === "L'" ? `l'${rest}` : `${article.toLowerCase()} ${rest}`;
  if (prep === 'de') {
    if (article === 'Les') return `${head} des ${rest}`;
    if (article === 'Le') return `${head} du ${rest}`;
    return `${head} de ${glued}`;
  }
  if (prep === 'à') {
    if (article === 'Les') return `${head} aux ${rest}`;
    if (article === 'Le') return `${head} au ${rest}`;
    return `${head} à ${glued}`;
  }
  return `${phrase} ${glued}`;
}
